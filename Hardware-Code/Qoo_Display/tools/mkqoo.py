"""Convert the DailyFlow QOO mascot art into big-endian RGB565 frames for the GC9309 panel.

QOO is drawn as a black robot lit by amber glow on a black ground, which is exactly what
this panel wants: the art's background and the panel's black are the same colour, so the
frames need no cutout and letterbox padding is invisible. Contain-fit is therefore used
rather than a crop - nothing of the character is ever cut off.
"""
import os
import sys
from PIL import Image

W, H = 240, 296
SP = os.path.dirname(os.path.abspath(__file__))
ART = r"C:\Users\Thejas\Desktop\Thejas\IQOO\Mobile-App\app\src\main\res\drawable-nodpi"
OUT_C = sys.argv[1]

# (source file, symbol, the Qoo enum state it mirrors in the app)
POSES = [
    ("qoo_sleeping.png", "qoo_sleeping", "Sleeping - not listening"),
    ("qoo_waving.png", "qoo_waving", "Waving - greeting / wake"),
    ("qoo_running.png", "qoo_running", "Running - capture in flight"),
    ("qoo_thinking.png", "qoo_thinking", "Thinking - extraction running"),
    ("qoo_resting.png", "qoo_resting", "Resting - all read, nothing open"),
]
# qoo_hero.png is deliberately excluded: it is a branding banner with baked-in text that
# is unreadable at 240 px, and it has no matching state in the app's Qoo enum.

BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


def contain_on_black(path):
    """Composite the RGBA art over black, then letterbox it into the panel without cropping."""
    src = Image.open(path).convert("RGBA")
    flat = Image.new("RGB", src.size, (0, 0, 0))
    flat.paste(src, mask=src.split()[3])          # alpha composite over black

    scale = min(W / src.width, H / src.height)
    fitted = flat.resize((max(1, int(src.width * scale)), max(1, int(src.height * scale))),
                         Image.LANCZOS)
    canvas = Image.new("RGB", (W, H), (0, 0, 0))
    canvas.paste(fitted, ((W - fitted.width) // 2, (H - fitted.height) // 2))
    return canvas


def to_rgb565_be(im):
    """Quantize to RGB565 with 4x4 ordered dithering; return big-endian bytes.

    The dither matters here: QOO's glow is a wide smooth amber falloff against black,
    which is exactly the gradient that bands worst at 5 bits of red.
    """
    px = im.load()
    out = bytearray()
    for y in range(H):
        row = BAYER[y & 3]
        for x in range(W):
            r, g, b = px[x, y][:3]
            t = (row[x & 3] - 7.5) / 16.0
            r = min(255, max(0, int(r + t * (255 / 31))))
            g = min(255, max(0, int(g + t * (255 / 63))))
            b = min(255, max(0, int(b + t * (255 / 31))))
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            out += bytes((v >> 8, v & 0xFF))      # big-endian: high byte first
    return out


with open(OUT_C, "w") as f:
    f.write("/* Generated by tools/mkqoo.py - do not edit.\n"
            " * %d x %d big-endian RGB565 frames of the DailyFlow QOO mascot.\n"
            " * Source art: Mobile-App/app/src/main/res/drawable-nodpi/\n */\n"
            '#include "qoo_frames.h"\n\n' % (W, H))
    for name, sym, role in POSES:
        im = contain_on_black(os.path.join(ART, name))
        im.save(os.path.join(SP, "preview_%s.png" % sym))
        data = to_rgb565_be(im)
        f.write("/* %s */\n" % role)
        f.write("const uint8_t %s[%d] = {\n" % (sym, len(data)))
        for i in range(0, len(data), 16):
            f.write("    " + "".join("0x%02X," % b for b in data[i:i + 16]) + "\n")
        f.write("};\n\n")
        print("%-18s -> %-14s %s" % (name, sym, role))
